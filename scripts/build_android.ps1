<#
.SYNOPSIS
  构建 Android APK（release 已签名 / debug）。

.DESCRIPTION
  自动定位 JDK 17+、Android SDK 与 Gradle：
    1) 命令行参数 -JavaHome / -SdkRoot / -GradleHome
    2) 环境变量 JAVA_HOME / ANDROID_HOME / ANDROID_SDK_ROOT / GRADLE_HOME
    3) 内置工具链 _las_toolchain（由 scripts\setup_toolchain.ps1 生成）

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\build_android.ps1
  powershell -ExecutionPolicy Bypass -File scripts\build_android.ps1 -Debug
#>
param(
    [string]$JavaHome = "",
    [string]$SdkRoot = "",
    [string]$GradleHome = "",
    [switch]$Debug
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$androidDir = Join-Path $root "android"
$dist = Join-Path $root "dist"
$toolchain = "C:\Users\Yuri\Desktop\_las_toolchain"
New-Item -ItemType Directory -Force -Path $dist | Out-Null

function Find-JavaHome {
    param([string]$Explicit)
    if ($Explicit -and (Test-Path (Join-Path $Explicit "bin\javac.exe"))) { return $Explicit }
    if ($env:JAVA_HOME -and (Test-Path (Join-Path $env:JAVA_HOME "bin\javac.exe"))) { return $env:JAVA_HOME }
    $bundled = Get-ChildItem $toolchain -Directory -Filter "jdk-*" -ErrorAction SilentlyContinue |
        Where-Object { Test-Path (Join-Path $_.FullName "bin\javac.exe") } |
        Select-Object -First 1 -ExpandProperty FullName
    if ($bundled) { return $bundled }
    throw "未找到 JDK 17+。请先运行 scripts\setup_toolchain.ps1，或用 -JavaHome 指定。"
}

function Find-SdkRoot {
    param([string]$Explicit)
    if ($Explicit -and (Test-Path (Join-Path $Explicit "platforms"))) { return $Explicit }
    if ($env:ANDROID_HOME -and (Test-Path (Join-Path $env:ANDROID_HOME "platforms"))) { return $env:ANDROID_HOME }
    if ($env:ANDROID_SDK_ROOT -and (Test-Path (Join-Path $env:ANDROID_SDK_ROOT "platforms"))) { return $env:ANDROID_SDK_ROOT }
    $bundled = Join-Path $toolchain "sdk"
    if (Test-Path (Join-Path $bundled "platforms")) { return $bundled }
    throw "未找到 Android SDK。请先运行 scripts\setup_toolchain.ps1，或用 -SdkRoot 指定。"
}

function Find-Gradle {
    param([string]$Explicit)
    if ($Explicit -and (Test-Path (Join-Path $Explicit "bin\gradle.bat"))) { return (Join-Path $Explicit "bin\gradle.bat") }
    if ($env:GRADLE_HOME -and (Test-Path (Join-Path $env:GRADLE_HOME "bin\gradle.bat"))) { return (Join-Path $env:GRADLE_HOME "bin\gradle.bat") }
    $bundled = Join-Path $toolchain "gradle-8.11.1\bin\gradle.bat"
    if (Test-Path $bundled) { return $bundled }
    $cmd = Get-Command gradle -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    throw "未找到 Gradle 8.9+。请先运行 scripts\setup_toolchain.ps1，或用 -GradleHome 指定。"
}

$java = Find-JavaHome $JavaHome
$sdk = Find-SdkRoot $SdkRoot
$gradle = Find-Gradle $GradleHome
Write-Host "JDK    : $java" -ForegroundColor Cyan
Write-Host "SDK    : $sdk" -ForegroundColor Cyan
Write-Host "Gradle : $gradle" -ForegroundColor Cyan

$env:JAVA_HOME = $java
$env:ANDROID_HOME = $sdk
$sdkDir = $sdk -replace "\\", "/"
"# generated by scripts/build_android.ps1`nsdk.dir=$sdkDir" |
    Set-Content -Path (Join-Path $androidDir "local.properties") -Encoding ASCII

$task = if ($Debug) { "assembleDebug" } else { "assembleRelease" }
Write-Host "==> gradle $task" -ForegroundColor Cyan
Push-Location $androidDir
try {
    & $gradle $task --no-daemon "-Dorg.gradle.java.home=$java"
    if ($LASTEXITCODE -ne 0) { throw "gradle 构建失败（exit $LASTEXITCODE）" }
} finally {
    Pop-Location
}

$apkDir = if ($Debug) {
    Join-Path $androidDir "app\build\outputs\apk\debug"
} else {
    Join-Path $androidDir "app\build\outputs\apk\release"
}
$apk = Get-ChildItem $apkDir -Filter "*.apk" | Sort-Object LastWriteTime -Descending | Select-Object -First 1
if (-not $apk) { throw "未找到 APK: $apkDir" }

$name = "LanAudioStream-1.0.0" + $(if ($Debug) { "-debug" } else { "" }) + ".apk"
$target = Join-Path $dist $name
Copy-Item $apk.FullName $target -Force

$apksigner = Join-Path $sdk "build-tools\35.0.0\apksigner.bat"
if ((Test-Path $apksigner) -and -not $Debug) {
    Write-Host "==> 校验 APK 签名" -ForegroundColor Cyan
    & $apksigner verify --print-certs $target | Select-Object -First 6
}

$aapt2 = Join-Path $sdk "build-tools\35.0.0\aapt2.exe"
$apkanalyzer = Join-Path $sdk "cmdline-tools\latest\bin\apkanalyzer.bat"
if ((Test-Path $aapt2) -and (Test-Path $apkanalyzer)) {
    Write-Host "==> 校验 AndroidManifest 引用的类是否都存在于 dex" -ForegroundColor Cyan
    $tree = & $aapt2 dump xmltree --file AndroidManifest.xml $target 2>$null
    $referenced = @()
    foreach ($line in $tree) {
        if ($line -match ':name\(0x01010003\)="([^"]+)"') { $referenced += $Matches[1] }
    }
    $referenced = $referenced | Where-Object { $_ -match '^\.' -or $_ -match '^com\.' } | Sort-Object -Unique
    $dexClasses = @()
    $pkgDump = & $apkanalyzer dex packages --defined-only $target 2>$null
    foreach ($line in $pkgDump) {
        if ($line -match '^C\s.*?\s([A-Za-z0-9_.$]+)\s*$') { $dexClasses += $Matches[1] }
    }
    if ($referenced.Count -eq 0) { throw "未能从 AndroidManifest 解析出任何组件类名，校验失效" }
    $missing = @()
    foreach ($c in $referenced) {
        if ($dexClasses -notcontains $c) { $missing += $c }
    }
    if ($missing.Count -gt 0) {
        throw "AndroidManifest 引用了 dex 中不存在的类（会导致启动即崩溃）: $($missing -join ', ')"
    }
    Write-Host "  通过：$($referenced -join ', ')" -ForegroundColor Green
}

$hash = (Get-FileHash $target -Algorithm SHA256).Hash
$size = [math]::Round((Get-Item $target).Length / 1MB, 2)
Write-Host ""
Write-Host "产物 : $target ($size MB)" -ForegroundColor Green
Write-Host "SHA256: $hash" -ForegroundColor Green
Write-Host "安装 : adb install -r `"$target`"" -ForegroundColor Green
